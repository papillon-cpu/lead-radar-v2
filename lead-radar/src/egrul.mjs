const strip = (s) =>
  s.toLowerCase().replace(/\s+/g, " ")
    .replace(/\(.*?\)/g, "")
    .replace(/^(г\.|г\s)\s*/i, "")
    .replace(/область$|обл\.?$|край$|республика$|автономный округ.*$|а\.о\.?$|округ$/i, "")
    .replace(/[\s—-]+/g, " ")
    .trim();

/** Регион по названию или коду: принимает "Тула", "Тульская область", "46", "Московская обл". */
export function resolveRegion(input) {
  const s = String(input || "").trim();
  if (!s) return "";
  if (REGIONS[s]) return s;
  const low = s.toLowerCase().replace(/\s+/g, " ");
  if (CITIES[low]) return CITIES[low];
  const norm = strip(s);
  for (const [code, name] of Object.entries(REGIONS)) {
    if (strip(name) === norm) return code;
  }
  for (const [code, name] of Object.entries(REGIONS)) {
    if (strip(name).includes(norm) || norm.includes(strip(name))) return code;
  }
  // «г. Курск» / «Курск» — ищем по названию региона, содержащему основу
  const base = norm.replace(/область$|обл\.?$|край$|республика$/i, "").trim();
  for (const [code, name] of Object.entries(REGIONS)) {
    const n = strip(name);
    if (n.startsWith(base) || base.startsWith(n)) return code;
  }
  const found = [...s.matchAll(/\d{2}/g)].map((m) => m[0]).find((c) => REGIONS[c]);
  return found || "";
}

async function getToken(query, region, fetchImpl) {
  const body = new URLSearchParams({ vyp3CaptchaToken: "", page: "", query, PreventChromeAutocomplete: "" });
  if (region) body.set("region", region);
  const res = await fetchImpl(BASE + "/", {
    method: "POST",
    headers: { "Content-Type": "application/x-www-form-urlencoded", "User-Agent": "Mozilla/5.0" },
    body: body.toString(),
  });
  if (!res.ok) throw new Error(`ФНС ответила ${res.status}`);
  const j = await res.json();
  if (j.captchaRequired) throw new Error("ФНС запросила капчу — попробуйте позже.");
  if (!j.t) throw new Error("ФНС не вернула токен поиска.");
  return j.t;
}

/** Поиск компаний и ИП по названию. Возвращает массив карточек. */
export async function searchEgrul({ query, region = "", limit = 20, fetchImpl = fetch }) {
  const q = String(query || "").trim();
  if (!q) throw new Error("Пустой запрос.");
  const reg = resolveRegion(region);
  const token = await getToken(q, reg, fetchImpl);
  const res = await fetchImpl(`${BASE}/search-result/${token}`, {
    headers: { "User-Agent": "Mozilla/5.0", "Referer": BASE + "/" },
  });
  if (!res.ok) throw new Error(`ФНС ответила ${res.status}`);
  const json = await res.json();
  const rows = Array.isArray(json?.rows) ? json.rows : [];
  return rows.slice(0, limit).map((r) => {
    const name = r.c || r.n || "";
    const isIP = r.k === "ip";
    return {
      name,
      fullName: r.n || "",
      inn: r.i || "",
      ogrn: r.o || "",
      status: r.t || "",
      regDate: r.e || r.r || "",
      region: r.rn || "",
      address: r.a || r.rn || "",
      director: (r.g || "").replace(/^ДИРЕКТОР:\s*/i, ""),
      kind: isIP ? "ИП" : "ЮЛ",
      source: "ЕГРЮЛ",
      site: "",
      phone: "",
      telegram: "",
    };
  });
}
